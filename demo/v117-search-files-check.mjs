import {chromium} from "playwright";
import assert from "node:assert/strict";
import {execSync} from "node:child_process";
if(!process.env.SKIM_SKIP_BUILD)execSync("npm run demo:build",{stdio:"pipe",windowsHide:true});
const browser=await chromium.launch();
try{
  const context=await browser.newContext({viewport:{width:1500,height:1000}});
  await context.addInitScript(()=>{
    localStorage.setItem("skimdemo.theme","base-dark");
    localStorage.setItem("skimdemo.fork_thread_multi","1");
    localStorage.setItem("skimdemo.fork_court_nudge","off");
    localStorage.setItem("skimdemo.search_match","older");
    window.__skimCalls=[];
  });
  const page=await context.newPage();page.setDefaultTimeout(12000);
  const errors=[];page.on("pageerror",error=>errors.push(String(error)));
  await page.goto(process.env.SKIM_DEMO_URL??"http://127.0.0.1:1431/");
  await page.keyboard.press("Control+k");
  await page.locator(".overlay .input-row input").fill("signed agreement");
  await page.locator(".hit-snippet mark").first().waitFor();
  assert.match(await page.locator(".hit-snippet").innerText(),/signed agreement/);
  await page.locator(".hit").click();
  await page.waitForFunction(()=>document.querySelector(".message[data-message-id]")?.getAttribute("data-message-id")==="1009");
  assert.match(await page.locator(".list").innerText(),/signed agreement/);
  await page.getByRole("button",{name:"Search & filters",exact:true}).click();
  await page.getByLabel("Attachment filename",{exact:true}).fill("proposal.pdf");
  await page.getByText("Filename search covers downloaded messages only.",{exact:false}).waitFor();
  await page.getByText("10 of 14 messages cached.",{exact:false}).waitFor();
  await page.getByRole("button",{name:"Files",exact:true}).click();
  const load=page.getByRole("button",{name:"Load remaining messages",exact:true});
  if(await load.count())await load.click();
  const files=page.locator(".conversation-tools .chips");
  await files.locator(".chip .name").first().click();
  const preview=page.getByRole("dialog",{name:"Attachment preview",exact:true});
  await preview.getByText("PDF text preview.",{exact:false}).waitFor();
  assert.match(await preview.locator("pre").innerText(),/Launch checklist/);
  const subject=await page.locator('.pane h1').textContent();
  await page.keyboard.press('e');await page.keyboard.press('Delete');
  assert.equal(await page.locator('.pane h1').textContent(),subject);
  await page.keyboard.press('Escape');await preview.waitFor({state:'hidden'});
  assert.equal(await page.locator('.pane h1').textContent(),subject);
  await files.locator('.chip .name').first().click();await preview.waitFor();
  await page.evaluate(()=>localStorage.setItem("skimdemo.attachment_save_error","on"));
  await preview.getByRole("button",{name:"Save file",exact:true}).click();
  await preview.getByRole("alert").getByText("Demo file could not save",{exact:true}).waitFor();
  await page.evaluate(()=>localStorage.removeItem("skimdemo.attachment_save_error"));
  await preview.getByRole("button",{name:"Open original",exact:true}).click();
  assert.ok(await page.evaluate(()=>window.__skimCalls.includes("open_attachment")));
  await preview.getByRole("button",{name:"Close attachment preview",exact:true}).click();
  await files.getByRole("button",{name:"Save all",exact:true}).click();
  await files.getByText("Saved 2 files.",{exact:true}).waitFor();
  assert.equal(await files.locator(".sources button").count(),2);
  await files.locator(".sources button").last().click();
  assert.deepEqual(errors,[]);
  console.log("PASS matching passage highlight, exact older message selection, preserved search, filename coverage, PDF text preview, Open original, Save all, source links");
}finally{await browser.close();}
